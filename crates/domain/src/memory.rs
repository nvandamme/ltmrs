#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quality_score_is_optional() {
        let score: Option<f64> = None;
        assert!(score.is_none());
        assert_eq!(Some(0.9), Some(0.9f64));
    }

    #[test]
    fn lifecycle_distinctions() {
        assert!(MemoryLifecycle::Live.is_recallable());
        assert!(
            !MemoryLifecycle::Invalidated {
                at: Instant::new(1)
            }
            .is_recallable()
        );
        assert!(
            !MemoryLifecycle::Archived {
                at: Instant::new(1)
            }
            .is_recallable()
        );
        assert!(
            !MemoryLifecycle::Deleted {
                at: Instant::new(1)
            }
            .is_recallable()
        );
    }

    /// Stable-id dual-write (Wave A3b): a memory carries the resolved
    /// `project_id` (ULID bits) alongside the frozen bare-string `project`
    /// for compat display/export; pre-wave rows decode as `None`.
    #[test]
    fn project_id_dual_writes_with_legacy_project() {
        use crate::id::EntityId;
        let pid = EntityId::new(uuid::Uuid::from_u128(0x0123));
        let m = Memory {
            id: EntityId::new(uuid::Uuid::from_u128(1)),
            external_alias: None,
            title: "t".into(),
            fragment: "f".into(),
            description: String::new(),
            fragment_type: FragmentType::Fact,
            project: Some("shop".into()),
            project_id: Some(pid),
            source: MemorySource::Ai,
            confidence: 0.5,
            quality_score: None,
            lifecycle: MemoryLifecycle::Live,
            tags: vec![],
            associated_with: vec![],
            relations: vec![],
            parent_id: None,
            child_ids: vec![],
            session_id: None,
            task_type: None,
            related_guides: vec![],
            evidence: vec![],
            access_count: 0,
            last_accessed_at: None,
            positive_feedback: 0,
            negative_feedback: 0,
            negative_hits: 0,
            refinement_count: 0,
            distill_candidate: false,
            entity_revision: EntityRevision::new(1),
            document_revision: DocumentRevision::new(1),
            eligibility_revision: EligibilityRevision::new(1),
            created_at: Instant::new(1000),
            updated_at: Instant::new(1000),
            raw_created: None,
            unknown_fields: std::collections::BTreeMap::new(),
        };
        assert_eq!(m.project_id, Some(pid));
        assert_eq!(m.project.as_deref(), Some("shop"));
        let mut v = serde_json::to_value(&m).unwrap();
        v.as_object_mut().unwrap().remove("project_id");
        let back: Memory = serde_json::from_value(v).unwrap();
        assert_eq!(back.project_id, None, "old rows load as None");
        assert_eq!(back.project.as_deref(), Some("shop"));
    }

    /// Provenance vocabulary: disjoint origins (user-typed, model-made,
    /// URL-captured, identified publication/volume, source tree).
    /// Verification state is NOT a source (see feedback counts).
    #[test]
    fn provenance_vocabulary_round_trips() {
        for (text, variant) in [
            ("user", MemorySource::User),
            ("ai", MemorySource::Ai),
            ("web", MemorySource::Web),
            ("paper", MemorySource::Paper),
            ("book", MemorySource::Book),
            ("code", MemorySource::Code),
        ] {
            assert_eq!(MemorySource::parse(text), Some(variant));
            assert_eq!(variant.as_str(), text);
            let json = serde_json::to_string(&variant).unwrap();
            assert_eq!(
                serde_json::from_str::<MemorySource>(&json).unwrap(),
                variant
            );
        }
        assert_eq!(MemorySource::parse("checked"), None);
        assert_eq!(MemorySource::parse("USER"), None);
    }
}
